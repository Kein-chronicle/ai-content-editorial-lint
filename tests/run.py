import os, subprocess, sys, tempfile
S = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "scripts"); ok = True
def run(*a): return subprocess.run([sys.executable, *a], capture_output=True, text=True).returncode
def expect(n, g, w):
    global ok; k = g == w; ok &= k; print(("ok   " if k else "FAIL ") + f"{n}: exit {g} (want {w})")
d = tempfile.mkdtemp()
def art(name, h2, extra=""): open(os.path.join(d, name), "w").write(f"---\ntitle: {name}\nstatus: published\n---\nintro\n\n## {h2}\n\ntext {extra}\n")
for i in range(6): art(f"a{i}.md", "Answer first")
expect("6/6 identical first headings => monoculture", run(os.path.join(S, "craft_lint.py"), d), 1)
d2 = tempfile.mkdtemp()
for i in range(6):
    open(os.path.join(d2, f"b{i}.md"), "w").write(f"---\ntitle: b{i}\n---\n\n## Heading number {i}\n\nbody\n")
expect("varied headings pass", run(os.path.join(S, "craft_lint.py"), d2), 0)
d3 = tempfile.mkdtemp(); open(os.path.join(d3, "x.md"), "w").write("## x\n")
expect("tiny corpus is unmeasured, not clean", run(os.path.join(S, "craft_lint.py"), d3), 3)
open(os.path.join(d2, "b0.md"), "a").write("AI generated. AI generated. AI generated.\n")
expect("disclaimer stuffing caught", run(os.path.join(S, "craft_lint.py"), d2, "--disclaimer", "AI generated"), 1)

p = os.path.join(d, "post.md"); r = os.path.join(d, "r.json")
open(p, "w").write("---\ntitle: T\nstatus: draft\n---\nBody text.\n")
expect("make receipt", run(os.path.join(S, "fingerprint.py"), "make", p, r), 0)
expect("unchanged passes", run(os.path.join(S, "fingerprint.py"), "check", p, r), 0)
open(p, "w").write("---\ntitle: T\nstatus: published\n---\nBody text.\n")
expect("status change alone is allowed", run(os.path.join(S, "fingerprint.py"), "check", p, r), 0)
open(p, "w").write("---\ntitle: T\nstatus: published\n---\nBody text, quietly edited.\n")
expect("silent body edit => drift", run(os.path.join(S, "fingerprint.py"), "check", p, r), 1)
open(p, "w").write("---\ntitle: Different\nstatus: published\n---\nBody text.\n")
expect("silent metadata edit => drift", run(os.path.join(S, "fingerprint.py"), "check", p, r), 1)
expect("missing receipt => cannot publish", run(os.path.join(S, "fingerprint.py"), "check", p, os.path.join(d, "none.json")), 1)

# --- review findings
q = os.path.join(d, "order.md"); rq = os.path.join(d, "order.json")
open(q, "w").write("---\ntitle: T\ntags:\n  - a\n  - b\n---\nBody.\n"); run(os.path.join(S, "fingerprint.py"), "make", q, rq)
open(q, "w").write("---\ntitle: T\ntags:\n  - b\n  - a\n---\nBody.\n")
expect("reordering frontmatter list items is a metadata edit => drift", run(os.path.join(S, "fingerprint.py"), "check", q, rq), 1)
expect("an unreadable post is exit 2", run(os.path.join(S, "fingerprint.py"), "make", os.path.join(d, "missing.md"), rq), 2)
dx = tempfile.mkdtemp()
for i in range(6): open(os.path.join(dx, f"p{i}.md"), "w").write(f"---\ntitle: p{i}\n---\n\n## Same opening\n\nbody {i}\n")
for i in range(8): open(os.path.join(dx, f"README{i}.md" if i == 0 else f"extra{i}.txt"), "w").write("# readme\n")
os.makedirs(os.path.join(dx, "node_modules", "pkg")); open(os.path.join(dx, "node_modules", "pkg", "x.md"), "w").write("# not an article\n")
for i in range(9): open(os.path.join(dx, "node_modules", "pkg", f"y{i}.md"), "w").write("# not an article\n")
expect("vendored folders and README files do not dilute the monoculture share", run(os.path.join(S, "craft_lint.py"), dx), 1)
dh = tempfile.mkdtemp()
for i in range(6): open(os.path.join(dh, f"h{i}.md"), "w").write("# Title\n\n### Same\n\nbody\n")
expect("articles without any '##' heading are unmeasured (3), not 'clean'", run(os.path.join(S, "craft_lint.py"), dh), 3)
df = tempfile.mkdtemp()
for i in range(6): open(os.path.join(df, f"f{i}.md"), "w").write("```\n## shell comment in a code fence\n```\n\n## Heading number %d\n" % i)
expect("a '##' line inside a code fence is not the article's opening heading", run(os.path.join(S, "craft_lint.py"), df), 0)
expect("--min-corpus 0 is refused (exit 2)", run(os.path.join(S, "craft_lint.py"), tempfile.mkdtemp(), "--min-corpus", "0"), 2)
open(os.path.join(dx, "bad.md"), "wb").write(b"\xff\xfe\x00bad")
expect("a non-UTF-8 file is exit 2, not a traceback", run(os.path.join(S, "craft_lint.py"), dx), 2)
sys.exit(0 if ok else 1)
